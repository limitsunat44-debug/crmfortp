-- ВНИМАНИЕ: проект работает через anon-ключ без Supabase Auth. Чтобы не сломать
-- текущее поведение (фронтенд сам читает/пишет эти таблицы), включаем RLS и
-- даём anon-роли полный доступ. Строгий вариант — в комментарии ниже; включать
-- после внедрения настоящей серверной авторизации.
ALTER TABLE crm_approved_devices  ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_login_attempts    ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_security_settings ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_approved_devices' AND policyname='devices_all_anon') THEN
        CREATE POLICY devices_all_anon ON crm_approved_devices FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_login_attempts' AND policyname='login_attempts_all_anon') THEN
        CREATE POLICY login_attempts_all_anon ON crm_login_attempts FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_security_settings' AND policyname='security_settings_all_anon') THEN
        CREATE POLICY security_settings_all_anon ON crm_security_settings FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;



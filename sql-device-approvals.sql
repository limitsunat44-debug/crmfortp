-- ============================================================================
-- CRM for TP — migration: одобрение устройств (вход только с разрешённых
-- устройств) + принудительный сброс всех сессий
-- ============================================================================
-- Назначение: сайт открывается публично, но ВХОД разрешён только с устройств,
-- которые администратор явно одобрил. Даже при верном логине/пароле вход с
-- неизвестного устройства не выполняется: создаётся заявка на одобрение,
-- админ видит её во вкладке «🔐 Устройства» и жмёт «Одобрить»/«Отклонить».
--
-- Дополнительно: глобальный «рубильник» crm_security_settings.session_version,
-- увеличение которого делает недействительными ВСЕ выданные ранее локальные
-- сессии (кнопка «Выйти из всех аккаунтов» в админ-панели).
--
-- Принципы (в стиле проекта, см. sql-daily-reports.sql):
--   * Все объекты создаются идемпотентно (IF NOT EXISTS / ON CONFLICT / DO $$).
--   * Файл можно запускать повторно — существующие данные НЕ удаляются.
--   * Frontend работает через anon-ключ без Supabase Auth, логин хранится в
--     строках (user_login), поэтому RLS включён, но anon-роли даётся полный
--     доступ — иначе сломается текущая модель. Строгий вариант — в конце файла.
--   * updated_at обслуживается общим триггером set_updated_at().
--
-- ВАЖНО: этот файл НЕ применяется автоматически. Запускать вручную в Supabase
-- SQL Editor. Никаких секретов (service_role, ключи) здесь нет и быть не должно.
--
-- ⚠️ ОГРАНИЧЕНИЕ БЕЗОПАСНОСТИ: это контроль на уровне UI + базы для статического
-- приложения на anon-ключе. Он останавливает обычного пользователя с чужим
-- паролем на чужом устройстве, но НЕ является криптографической привязкой к
-- устройству: у клиента есть anon-ключ, и технически подготовленный человек
-- может обращаться к REST напрямую. Настоящая привязка требует серверной
-- авторизации (Supabase Auth / edge function), проверяющей device_id на
-- сервере при выдаче токена.
-- ============================================================================

-- Общий триггер обновления updated_at (создаётся в других миграциях; дублируем
-- идемпотентно, чтобы файл можно было запускать автономно).
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ===========================================================================
-- 1. crm_approved_devices — заявки и разрешения на устройства
-- ===========================================================================
-- Одна строка на пару (user_login, device_id).
--   status = 'pending'  — заявка создана при попытке входа, ждёт админа;
--            'approved' — вход с этого устройства разрешён;
--            'rejected' — отклонено/отозвано (запись сохраняем как историю,
--                         повторные попытки входа НЕ переводят её в pending).
--   device_id  — случайный UUID, который фронтенд хранит в localStorage
--                (ключ crm_device_id). Это НЕ отпечаток браузера: очистка
--                localStorage создаст новое устройство → новую заявку.
--   metadata   — безопасные для отображения данные: user agent, платформа,
--                язык, таймзона, разрешение экрана, first_seen/last_seen,
--                requested_login, last_ip (NULL — фронтенд IP не знает).
CREATE TABLE IF NOT EXISTS crm_approved_devices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_login   TEXT NOT NULL,
    device_id    TEXT NOT NULL,
    status       TEXT NOT NULL DEFAULT 'pending',   -- 'pending' | 'approved' | 'rejected'
    device_name  TEXT,                              -- краткое имя, напр. «Chrome 120 · Windows»
    metadata     JSONB NOT NULL DEFAULT '{}'::jsonb,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    approved_at  TIMESTAMPTZ,
    approved_by  TEXT,                              -- логин админа
    rejected_at  TIMESTAMPTZ,
    rejected_by  TEXT,
    notes        TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_crm_approved_device UNIQUE (user_login, device_id)
);

-- Ограничение на допустимые статусы. Добавляем идемпотентно и только если
-- существующие данные ему не противоречат (иначе миграция упала бы).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_crm_approved_devices_status'
          AND conrelid = 'crm_approved_devices'::regclass
    ) AND NOT EXISTS (
        SELECT 1 FROM crm_approved_devices
        WHERE status NOT IN ('pending', 'approved', 'rejected')
    ) THEN
        ALTER TABLE crm_approved_devices
            ADD CONSTRAINT chk_crm_approved_devices_status
            CHECK (status IN ('pending', 'approved', 'rejected'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_crm_approved_devices_login  ON crm_approved_devices (user_login);
CREATE INDEX IF NOT EXISTS idx_crm_approved_devices_device ON crm_approved_devices (device_id);
CREATE INDEX IF NOT EXISTS idx_crm_approved_devices_status ON crm_approved_devices (status);
CREATE INDEX IF NOT EXISTS idx_crm_approved_devices_req_at ON crm_approved_devices (requested_at DESC);

DROP TRIGGER IF EXISTS trg_crm_approved_devices_updated_at ON crm_approved_devices;
CREATE TRIGGER trg_crm_approved_devices_updated_at
    BEFORE UPDATE ON crm_approved_devices
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Автоматически проставляем approved_at / rejected_at при смене статуса, чтобы
-- фронтенду не нужно было помнить об этом (и чтобы данные не разъезжались).
CREATE OR REPLACE FUNCTION crm_devices_stamp_status()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'approved' AND (OLD.status IS DISTINCT FROM 'approved' OR NEW.approved_at IS NULL) THEN
        NEW.approved_at = COALESCE(NEW.approved_at, NOW());
    END IF;
    IF NEW.status = 'rejected' AND (OLD.status IS DISTINCT FROM 'rejected' OR NEW.rejected_at IS NULL) THEN
        NEW.rejected_at = COALESCE(NEW.rejected_at, NOW());
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_crm_approved_devices_stamp ON crm_approved_devices;
CREATE TRIGGER trg_crm_approved_devices_stamp
    BEFORE UPDATE ON crm_approved_devices
    FOR EACH ROW EXECUTE FUNCTION crm_devices_stamp_status();



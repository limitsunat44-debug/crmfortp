CREATE INDEX IF NOT EXISTS idx_crm_login_attempts_login   ON crm_login_attempts (user_login);
CREATE INDEX IF NOT EXISTS idx_crm_login_attempts_device  ON crm_login_attempts (device_id);
CREATE INDEX IF NOT EXISTS idx_crm_login_attempts_created ON crm_login_attempts (created_at DESC);


-- ===========================================================================
-- 3. crm_security_settings — глобальные настройки безопасности (одна строка)
-- ===========================================================================
-- session_version  — «эпоха» сессий. Фронтенд сохраняет её в localStorage при
--                    входе и сверяет при загрузке/навигации. Увеличили версию
--                    → все ранее выданные локальные сессии стали недействительны.
-- force_logout_at  — момент принудительного выхода: сессии, выданные раньше,
--                    считаются недействительными (страховка на случай, если
--                    session_version по какой-то причине совпал).
CREATE TABLE IF NOT EXISTS crm_security_settings (
    id              SMALLINT PRIMARY KEY DEFAULT 1,
    session_version INTEGER NOT NULL DEFAULT 1,
    force_logout_at TIMESTAMPTZ,
    updated_by      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_crm_security_settings_single_row CHECK (id = 1)
);

DROP TRIGGER IF EXISTS trg_crm_security_settings_updated_at ON crm_security_settings;
CREATE TRIGGER trg_crm_security_settings_updated_at
    BEFORE UPDATE ON crm_security_settings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Единственная строка. Идемпотентно: повторный запуск НЕ сбрасывает версию.
INSERT INTO crm_security_settings (id, session_version, updated_by)
VALUES (1, 1, 'migration')
ON CONFLICT (id) DO NOTHING;


-- ===========================================================================
-- 4. crm_bump_session_version() — атомарный сброс всех сессий
-- ===========================================================================
-- Вызывается кнопкой «🚪 Выйти из всех аккаунтов» через PostgREST RPC:
--   POST /rest/v1/rpc/crm_bump_session_version  {"p_admin_login": "admin1"}
-- Атомарный инкремент важен: два админа, нажавшие кнопку одновременно, не
-- перезапишут версию друг друга (в отличие от «прочитать и записать» с клиента).
CREATE OR REPLACE FUNCTION crm_bump_session_version(p_admin_login TEXT DEFAULT NULL)
RETURNS TABLE (new_session_version INTEGER, new_force_logout_at TIMESTAMPTZ)
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO crm_security_settings AS s (id, session_version, force_logout_at, updated_by)
    VALUES (1, 2, NOW(), p_admin_login)
    ON CONFLICT (id) DO UPDATE
        SET session_version = s.session_version + 1,
            force_logout_at = NOW(),
            updated_by      = COALESCE(p_admin_login, s.updated_by)
    RETURNING s.session_version, s.force_logout_at
    INTO new_session_version, new_force_logout_at;

    RETURN NEXT;
END;
$$;

GRANT EXECUTE ON FUNCTION crm_bump_session_version(TEXT) TO anon, authenticated;



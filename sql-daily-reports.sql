-- ===========================================================================
-- RLS / POLICIES (в стиле проекта: anon имеет полный доступ)
-- ===========================================================================
-- ВНИМАНИЕ: проект работает через anon-ключ без Supabase Auth. Чтобы не сломать
-- текущее поведение, включаем RLS и даём anon-роли полный доступ. Более строгий
-- вариант (ТП видит только свои отчёты) — в комментарии в конце файла; включать
-- после внедрения настоящей авторизации.
ALTER TABLE crm_daily_report_questions          ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_daily_report_question_overrides ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_daily_reports                   ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_daily_report_answers            ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_daily_report_questions' AND policyname='dr_questions_all_anon') THEN
        CREATE POLICY dr_questions_all_anon ON crm_daily_report_questions FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_daily_report_question_overrides' AND policyname='dr_overrides_all_anon') THEN
        CREATE POLICY dr_overrides_all_anon ON crm_daily_report_question_overrides FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_daily_reports' AND policyname='dr_reports_all_anon') THEN
        CREATE POLICY dr_reports_all_anon ON crm_daily_reports FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_daily_report_answers' AND policyname='dr_answers_all_anon') THEN
        CREATE POLICY dr_answers_all_anon ON crm_daily_report_answers FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;


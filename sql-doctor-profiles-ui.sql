-- ===========================================================================
-- RLS / POLICIES (в стиле проекта: anon read+write)
-- ===========================================================================
ALTER TABLE crm_doctor_specialties ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_doctor_specialties' AND policyname='doctor_specialties_read') THEN
        CREATE POLICY doctor_specialties_read ON crm_doctor_specialties FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_doctor_specialties' AND policyname='doctor_specialties_write_anon') THEN
        CREATE POLICY doctor_specialties_write_anon ON crm_doctor_specialties FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;


-- ===========================================================================
-- 7. crm_rep_points_ledger — журнал баллов ТП
-- ===========================================================================
-- Правила: 1 посещённый врач = +1 балл. Админ может начислить/списать вручную.
-- reason: 'visit' | 'payment_on_time' | 'manual_credit' | 'manual_debit'
CREATE TABLE IF NOT EXISTS crm_rep_points_ledger (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rep_login    TEXT NOT NULL,
    points       INTEGER NOT NULL DEFAULT 0,   -- может быть отрицательным (списание)
    reason       TEXT NOT NULL DEFAULT 'manual_credit',
    ref_type     TEXT,                          -- 'visit' | 'payment' | 'plan' | NULL
    ref_id       TEXT,                          -- id связанной сущности (для идемпотентности)
    comment      TEXT,
    created_by   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_points_rep    ON crm_rep_points_ledger (rep_login);
CREATE INDEX IF NOT EXISTS idx_points_reason  ON crm_rep_points_ledger (reason);
CREATE INDEX IF NOT EXISTS idx_points_created  ON crm_rep_points_ledger (created_at);
-- защита от двойного начисления за один и тот же визит
CREATE UNIQUE INDEX IF NOT EXISTS uq_points_visit
    ON crm_rep_points_ledger (rep_login, ref_type, ref_id)
    WHERE ref_type IS NOT NULL AND ref_id IS NOT NULL;

DROP TRIGGER IF EXISTS trg_points_updated_at ON crm_rep_points_ledger;
CREATE TRIGGER trg_points_updated_at
    BEFORE UPDATE ON crm_rep_points_ledger
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();



-- ===========================================================================
-- 4. crm_doctor_bonus_periods — представление сверки 1С vs DocSales + бонусы
-- ===========================================================================
-- Бизнес-правила:
--   итого к выплате = onec_amount * 0.10 + onec_checks_count * 10
--   bonus_10        = onec_amount * 0.10
--   bonus_patients  = onec_checks_count * 10  (1 чек = 1 пациент = 10)
--   diff_percent    = |onec - docsales| / onec * 100
--   разница > 10 %  => статус сверки 'mismatch' (подсветка во frontend)
CREATE OR REPLACE VIEW crm_doctor_bonus_periods AS
SELECT
    o.doctor_code,
    d.doctor_name,
    o.period_start,
    o.period_end,
    o.amount                                    AS onec_amount,
    o.checks_count                              AS onec_checks_count,
    COALESCE(ds.amount, 0)                       AS docsales_amount,
    COALESCE(ds.checks_count, 0)                 AS docsales_checks_count,
    CASE
        WHEN o.amount IS NULL OR o.amount = 0 THEN NULL
        ELSE ROUND(ABS(o.amount - COALESCE(ds.amount, 0)) / o.amount * 100, 2)
    END                                          AS diff_percent,
    ROUND(o.amount * 0.10, 2)                     AS bonus_10,
    (o.checks_count * 10)                         AS bonus_patients,
    ROUND(o.amount * 0.10 + o.checks_count * 10, 2) AS total_payable,
    CASE
        WHEN o.amount IS NULL OR o.amount = 0 THEN 'no_data'
        WHEN ABS(o.amount - COALESCE(ds.amount, 0)) / o.amount * 100 > 10 THEN 'mismatch'
        ELSE 'matched'
    END                                          AS reconciliation_status
FROM crm_onec_sales_cache o
LEFT JOIN crm_doctors d
    ON d.doctor_code = o.doctor_code
LEFT JOIN crm_docsales_sales_cache ds
    ON ds.doctor_code = o.doctor_code
   AND ds.period_start = o.period_start
   AND ds.period_end   = o.period_end;



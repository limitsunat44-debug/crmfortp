-- RLS / POLICIES
-- ===========================================================================
-- ВНИМАНИЕ: текущий проект работает через anon-ключ и не использует Supabase Auth.
-- Чтобы не ломать существующее поведение, по умолчанию включаем RLS и даём
-- anon-роли полный доступ к операционным таблицам, а кэш-таблицы 1С/DocSales
-- делаем read-only для anon (писать в них должен только service_role-синк).

ALTER TABLE crm_doctors              ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_onec_sales_cache     ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_docsales_sales_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_doctor_payments      ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_rep_plan_items       ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_rep_points_ledger    ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_sync_runs            ENABLE ROW LEVEL SECURITY;

-- ---- Кэш-таблицы: чтение всем (anon+authenticated), запись — только service_role
DO $$
BEGIN
    -- crm_doctors
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_doctors' AND policyname='crm_doctors_read') THEN
        CREATE POLICY crm_doctors_read ON crm_doctors FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_doctors' AND policyname='crm_doctors_write_anon') THEN
        -- проект сейчас добавляет врачей из frontend через anon — разрешаем
        CREATE POLICY crm_doctors_write_anon ON crm_doctors FOR ALL USING (true) WITH CHECK (true);
    END IF;

    -- crm_onec_sales_cache (read-only для anon)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_onec_sales_cache' AND policyname='onec_cache_read') THEN
        CREATE POLICY onec_cache_read ON crm_onec_sales_cache FOR SELECT USING (true);
    END IF;

    -- crm_docsales_sales_cache (read-only для anon)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_docsales_sales_cache' AND policyname='docsales_cache_read') THEN
        CREATE POLICY docsales_cache_read ON crm_docsales_sales_cache FOR SELECT USING (true);
    END IF;

    -- crm_doctor_payments (full anon — в стиле проекта)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_doctor_payments' AND policyname='payments_all_anon') THEN
        CREATE POLICY payments_all_anon ON crm_doctor_payments FOR ALL USING (true) WITH CHECK (true);
    END IF;

    -- crm_rep_plan_items (full anon)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_rep_plan_items' AND policyname='plan_all_anon') THEN
        CREATE POLICY plan_all_anon ON crm_rep_plan_items FOR ALL USING (true) WITH CHECK (true);
    END IF;

    -- crm_rep_points_ledger (full anon)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_rep_points_ledger' AND policyname='points_all_anon') THEN
        CREATE POLICY points_all_anon ON crm_rep_points_ledger FOR ALL USING (true) WITH CHECK (true);
    END IF;

    -- crm_sync_runs (read-only для anon; пишет backend через service_role)
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='crm_sync_runs' AND policyname='sync_runs_read') THEN
        CREATE POLICY sync_runs_read ON crm_sync_runs FOR SELECT USING (true);
    END IF;
END $$;


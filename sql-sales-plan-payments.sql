-- Назначение: добавить таблицы-кэши и операционные таблицы для новых вкладок
-- (Продажи, Выплаты, План, Профиль ТП, Админ-статистика).
--
-- Принципы:
--   * Все объекты создаются идемпотентно (IF NOT EXISTS).
--   * Frontend читает ТОЛЬКО кэш-таблицы Supabase (crm_onec_sales_cache,
--     crm_docsales_sales_cache, crm_doctors). Реальная синхронизация с 1С (OData)
--     и DocSales выполняется отдельным backend-процессом (service_role / RPC),
--     потому что:
--       - логин/пароль 1С НЕЛЬЗЯ держать во frontend;
--       - OData $filter по Period/Description/Parent_Key в этой базе падает,
--         поэтому выборку нужно делать server-side и складывать в кэш.
--   * Политики RLS сделаны "в стиле проекта": проект сейчас работает через
--     anon-ключ и хранит логин внутри строк (user_login / rep_login). Поэтому
--     по умолчанию разрешаем чтение/запись анонимной роли, чтобы не сломать
--     текущую (небезопасную) модель доступа. Раздел в конце файла содержит
--     более строгий вариант политик — включить после внедрения настоящей авторизации.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Общий триггер для автоматического обновления updated_at
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ===========================================================================
-- 1. crm_doctors — справочник врачей (кэш из 1С / DocSales)
-- ===========================================================================
CREATE TABLE IF NOT EXISTS crm_doctors (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_code        TEXT NOT NULL UNIQUE,          -- КодКарты / Code из 1С
    doctor_name        TEXT,                          -- Description
    discount_card_ref  TEXT,                          -- Ref_Key карты в 1С
    discount_card_code TEXT,                          -- КодКарты
    source             TEXT DEFAULT 'onec',           -- 'onec' | 'docsales' | 'manual'
    discount_group     TEXT,                          -- ВидДисконтнойКарты_Key / Parent_Key
    active             BOOLEAN DEFAULT TRUE,
    last_synced_at     TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_crm_doctors_code   ON crm_doctors (doctor_code);
CREATE INDEX IF NOT EXISTS idx_crm_doctors_active ON crm_doctors (active);
CREATE INDEX IF NOT EXISTS idx_crm_doctors_source ON crm_doctors (source);

DROP TRIGGER IF EXISTS trg_crm_doctors_updated_at ON crm_doctors;
CREATE TRIGGER trg_crm_doctors_updated_at
    BEFORE UPDATE ON crm_doctors
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- ===========================================================================
-- 2. crm_onec_sales_cache — кэш продаж из 1С (AccumulationRegister)
-- ===========================================================================
-- Источник: AccumulationRegister_ПродажиПоДисконтнымКартам_RecordType
-- Поля 1С: Period, Recorder, Active, ДисконтнаяКарта_Key, Сумма, Количество.
-- Заполняется ТОЛЬКО backend-синхронизацией (service_role).
CREATE TABLE IF NOT EXISTS crm_onec_sales_cache (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_code   TEXT NOT NULL,
    period_start  DATE,                  -- начало периода агрегации
    period_end    DATE,                  -- конец периода агрегации
    sale_date     DATE,                  -- дата отдельной записи (если хранится детально)
    recorder      TEXT,                  -- Recorder (ссылка на документ-регистратор)
    amount        NUMERIC(14,2) DEFAULT 0,   -- Сумма (продажи 1С)
    checks_count  INTEGER DEFAULT 0,         -- Количество (чеки 1С = пациенты)
    raw           JSONB,                     -- сырой ответ OData (для отладки)
    synced_at     TIMESTAMPTZ DEFAULT NOW(),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_onec_cache_doctor  ON crm_onec_sales_cache (doctor_code);
CREATE INDEX IF NOT EXISTS idx_onec_cache_period  ON crm_onec_sales_cache (period_start, period_end);
CREATE INDEX IF NOT EXISTS idx_onec_cache_saledate ON crm_onec_sales_cache (sale_date);
-- уникальность строки агрегации по врачу+периоду (для UPSERT из синка)
CREATE UNIQUE INDEX IF NOT EXISTS uq_onec_cache_doc_period
    ON crm_onec_sales_cache (doctor_code, period_start, period_end);

DROP TRIGGER IF EXISTS trg_onec_cache_updated_at ON crm_onec_sales_cache;
